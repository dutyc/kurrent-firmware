#!/usr/bin/env python3
"""Generate the embedded Secure Boot enrollment descriptors.

Builds three authenticated variable payloads (PK, KEK, db) for
SetVariable() and writes them as a C header that sbenroll_cmd.c
includes.  Only public certificates and signatures reach the header;
private keys are read by sbvarsign and never copied.

PK is signed by the PK key, KEK by the PK key, and db by the KEK key.
The db payload carries the artifact signing certificate followed by
the Microsoft UEFI CA 2011 certificate.
"""

import argparse
import struct
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

EFI_GLOBAL_VARIABLE = "8be4df61-93ca-11d2-aa0d-00e098032b8c"
EFI_IMAGE_SECURITY_DATABASE = "d719b2cb-3d3a-4596-a3bc-dad00e67656f"
EFI_CERT_X509_GUID = uuid.UUID("a5c059a1-94e4-4aa7-87b5-ab155c2bf072")
ATTRS = ("NON_VOLATILE,BOOTSERVICE_ACCESS,RUNTIME_ACCESS,"
         "TIME_BASED_AUTHENTICATED_WRITE_ACCESS")


def der(cert: Path) -> bytes:
    return subprocess.run(
        ["openssl", "x509", "-in", str(cert), "-outform", "DER"],
        check=True, capture_output=True).stdout


def esl(certs, owner: uuid.UUID) -> bytes:
    """Build an EFI_SIGNATURE_LIST containing one X.509 entry per cert."""
    out = bytearray()
    for cert in certs:
        body = owner.bytes_le + der(cert)
        out += EFI_CERT_X509_GUID.bytes_le
        out += struct.pack("<III", 28 + len(body), 0, len(body))
        out += body
    return bytes(out)


def sign(var: str, data: bytes, key: Path, cert: Path, guid: str) -> bytes:
    with tempfile.TemporaryDirectory() as tmp:
        esl_path = Path(tmp) / f"{var}.esl"
        auth_path = Path(tmp) / f"{var}.auth"
        esl_path.write_bytes(data)
        subprocess.run(
            ["sbvarsign", "--key", str(key), "--cert", str(cert),
             "--guid", guid, "--attr", ATTRS,
             "--output", str(auth_path), var, str(esl_path)],
            check=True)
        return auth_path.read_bytes()


def carray(name: str, data: bytes) -> str:
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[] = {{ {body} }};\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pk-key", required=True, type=Path)
    ap.add_argument("--pk-cert", required=True, type=Path)
    ap.add_argument("--kek-key", required=True, type=Path)
    ap.add_argument("--kek-cert", required=True, type=Path)
    ap.add_argument("--db-cert", required=True, type=Path,
                    help="artifact signing certificate")
    ap.add_argument("--ms-ca", required=True, type=Path,
                    help="Microsoft UEFI CA 2011 certificate")
    ap.add_argument("--owner-guid", default="a0baa8a3-041d-48a8-bc87-c36d121b5e3d")
    ap.add_argument("--output", required=True, type=Path)
    args = ap.parse_args()

    owner = uuid.UUID(args.owner_guid)
    pk_esl = esl([args.pk_cert], owner)
    kek_esl = esl([args.kek_cert], owner)
    db_esl = esl([args.db_cert, args.ms_ca], owner)

    blobs = {
        "pk_esl": pk_esl,
        "pk_auth": sign("PK", pk_esl, args.pk_key, args.pk_cert, EFI_GLOBAL_VARIABLE),
        "kek_esl": kek_esl,
        "kek_auth": sign("KEK", kek_esl, args.pk_key, args.pk_cert, EFI_GLOBAL_VARIABLE),
        "db_esl": db_esl,
        "db_auth": sign("db", db_esl, args.kek_key, args.kek_cert, EFI_IMAGE_SECURITY_DATABASE),
    }

    text = ["/* Generated by build/sbenroll-gen.py; do not edit. */\n",
            "#ifndef _IPXE_SBENROLL_DATA_H\n#define _IPXE_SBENROLL_DATA_H\n\n",
            "#define SBENROLL_ENROLL_DATA 1\n\n"]
    for name, data in blobs.items():
        text.append(carray(f"sbenroll_{name}", data))
    text.append("\n#endif /* _IPXE_SBENROLL_DATA_H */\n")

    args.output.write_text("".join(text))
    for name, data in blobs.items():
        print(f"sbenroll: {name} {len(data)} bytes")
    print(f"sbenroll: wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
