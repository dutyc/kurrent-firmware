/** Test TLS 1.3 ClientHello construction */
static void tls13_client_hello_test ( void ) {
	struct digest_algorithm *digest = &sha256_algorithm;
	size_t id_len = strlen ( test_identity );
	uint8_t ch[ 1024 ];
	uint8_t early[ digest->digestsize ];
	uint8_t binder[ digest->digestsize ];
	size_t prefix_len;
	size_t len;
	size_t i;
	int found;

	len = tls13_client_hello ( ch, sizeof ( ch ), test_random,
				   test_public_key, resumption_psk,
				   sizeof ( resumption_psk ), test_identity,
				   id_len, "ext binder" );
	ok ( len != 0 );

	/* Handshake header */
	ok ( ch[0] == TLS_CLIENT_HELLO );
	ok ( ( size_t ) ( ( ch[1] << 16 ) | ( ch[2] << 8 ) | ch[3] )
	     == ( len - 4 ) );

	/* legacy_version, random, legacy_session_id */
	ok ( ( ch[4] == 0x03 ) && ( ch[5] == 0x03 ) );
	ok ( memcmp ( &ch[6], test_random, sizeof ( test_random ) ) == 0 );
	ok ( ch[38] == 0x00 );

	/* cipher_suites = { TLS_AES_128_GCM_SHA256 }, compression = { null } */
	ok ( ( ch[39] == 0x00 ) && ( ch[40] == 0x02 ) );
	ok ( ( ch[41] == 0x13 ) && ( ch[42] == 0x01 ) );
	ok ( ( ch[43] == 0x01 ) && ( ch[44] == 0x00 ) );

	/* PSK identity must appear verbatim */
	found = 0;
	for ( i = 0 ; ( i + id_len ) <= len ; i++ ) {
		if ( memcmp ( &ch[i], test_identity, id_len ) == 0 ) {
			found = 1;
			break;
		}
	}
	ok ( found );

	/* The extension block must be well-formed (RFC 8446 section 4.2).
	 *
	 * Walk the extensions produced by tls13_client_hello() and check
	 * each list-encoded field, so that every offset and length within
	 * the message is independently verified rather than trusted.
	 */
	{
		size_t p = 47;		/* past the compression methods */
		size_t eend;
		uint16_t type;
		uint16_t elen;

		/* The extensions block ends at the end of the message,
		 * since the final extension contains the binders list.
		 */
		eend = ( p + ( ( ch[45] << 8 ) | ch[46] ) );
		ok ( eend == len );

		/* supported_versions = { TLS 1.3 }; the version list
		 * carries a one-byte length prefix.
		 */
		type = ( ( ch[p] << 8 ) | ch[p+1] );
		elen = ( ( ch[p+2] << 8 ) | ch[p+3] );
		ok ( type == TLS_SUPPORTED_VERSIONS );
		ok ( elen == 3 );
		ok ( ch[p+4] == 2 );
		ok ( ( ch[p+5] == 0x03 ) && ( ch[p+6] == 0x04 ) );
		p += ( 4 + elen );

		/* supported_groups = { x25519 }; the named group list
		 * carries a two-byte length prefix.
		 */
		type = ( ( ch[p] << 8 ) | ch[p+1] );
		elen = ( ( ch[p+2] << 8 ) | ch[p+3] );
		ok ( type == TLS_NAMED_GROUP );
		ok ( elen == 4 );
		ok ( ( ( ch[p+4] << 8 ) | ch[p+5] ) == 2 );
		ok ( ( ( ch[p+6] << 8 ) | ch[p+7] ) == TLS_NAMED_GROUP_X25519 );
		p += ( 4 + elen );

		/* key_share = { x25519: public_key }; the client shares
		 * list carries a two-byte length prefix.
		 */
		type = ( ( ch[p] << 8 ) | ch[p+1] );
		elen = ( ( ch[p+2] << 8 ) | ch[p+3] );
		ok ( type == TLS_KEY_SHARE );
		ok ( elen == 38 );
		ok ( ( ( ch[p+4] << 8 ) | ch[p+5] ) == 36 );
		ok ( ( ( ch[p+6] << 8 ) | ch[p+7] ) == TLS_NAMED_GROUP_X25519 );
		ok ( ( ( ch[p+8] << 8 ) | ch[p+9] ) == 32 );
		ok ( memcmp ( &ch[p+10], test_public_key,
			      sizeof ( test_public_key ) ) == 0 );
		p += ( 4 + elen );

		/* psk_key_exchange_modes = { psk_dhe_ke }; the mode list
		 * carries a one-byte length prefix.
		 */
		type = ( ( ch[p] << 8 ) | ch[p+1] );
		elen = ( ( ch[p+2] << 8 ) | ch[p+3] );
		ok ( type == TLS_PSK_KEY_EXCHANGE_MODES );
		ok ( elen == 2 );
		ok ( ch[p+4] == 1 );
		ok ( ch[p+5] == TLS_PSK_KEY_EXCHANGE_MODE_PSK_DHE );
		p += ( 4 + elen );

		/* pre_shared_key must be the final extension */
		type = ( ( ch[p] << 8 ) | ch[p+1] );
		elen = ( ( ch[p+2] << 8 ) | ch[p+3] );
		ok ( type == TLS_PRE_SHARED_KEY );
		ok ( ( p + 4 + elen ) == eend );
	}

	/* The final extension is pre_shared_key: binders list + binder */
	prefix_len = ( len - ( 2 + 1 + digest->digestsize ) );
	ok ( ch[prefix_len] == 0x00 );
	ok ( ch[prefix_len + 1] == ( uint8_t ) ( 1 + digest->digestsize ) );
	ok ( ch[prefix_len + 2] == ( uint8_t ) digest->digestsize );
	tls13_early_secret ( digest, resumption_psk, sizeof ( resumption_psk ),
			     early );
	tls13_binder ( digest, early, "ext binder", ch, prefix_len, binder );
	ok ( memcmp ( &ch[prefix_len + 3], binder, sizeof ( binder ) ) == 0 );
}

/** Test TLS 1.3 record nonce construction */
static void tls13_nonce_test ( void ) {
	uint8_t expected[ TLS13_NONCE_LEN ];
	uint8_t nonce[ TLS13_NONCE_LEN ];
	unsigned int i;

	/* Sequence number zero leaves the IV unchanged */
	tls13_nonce ( client_app_iv, 0, nonce );
	tls13_okx ( "nonce(0)", nonce, client_app_iv, sizeof ( nonce ) );

	/* Sequence number one XORs into the final byte */
	memcpy ( expected, client_app_iv, sizeof ( expected ) );
	expected[ TLS13_NONCE_LEN - 1 ] ^= 0x01;
	tls13_nonce ( client_app_iv, 1, nonce );
	tls13_okx ( "nonce(1)", nonce, expected, sizeof ( nonce ) );

	/* Multi-byte sequence numbers XOR into the final eight bytes */
	memcpy ( expected, client_app_iv, sizeof ( expected ) );
	for ( i = 0 ; i < 8 ; i++ )
		expected[ TLS13_NONCE_LEN - 8 + i ] ^= ( 0x0102030405060708ULL
							 >> ( 8 * ( 7 - i ) ) );
	tls13_nonce ( client_app_iv, 0x0102030405060708ULL, nonce );
	tls13_okx ( "nonce(64-bit)", nonce, expected, sizeof ( nonce ) );
}

/** Test TLS 1.3 record sealing and opening against RFC 8448 section 3 */
static void tls13_record_test ( void ) {
	struct cipher_algorithm *cipher = &aes_gcm_algorithm;
	uint8_t header[] = APP_RECORD_HEADER ( sizeof ( client_app_record ) );
	uint8_t sealed[ 128 ];
	uint8_t opened[ 128 ];
	uint8_t tampered[ sizeof ( client_app_record ) ];
	size_t len;
	int content_type;

	/* Seal client application_data at sequence number zero */
	len = tls13_seal ( cipher, client_app_key, sizeof ( client_app_key ),
			   client_app_iv, 0, header, sizeof ( header ),
			   app_payload, sizeof ( app_payload ), TLS_TYPE_DATA,
			   sealed );
	ok ( len == sizeof ( client_app_record ) );
	tls13_okx ( "seal(client)", sealed, client_app_record, len );

	/* Open client application_data at sequence number zero */
	content_type = tls13_open ( cipher, client_app_key,
				    sizeof ( client_app_key ), client_app_iv, 0,
				    header, sizeof ( header ),
				    client_app_record, sizeof ( client_app_record ),
				    opened, &len );
	ok ( content_type == TLS_TYPE_DATA );
	ok ( len == sizeof ( app_payload ) );
	tls13_okx ( "open(client)", opened, app_payload, len );

	/* Server application_data uses sequence number one (sequence
	 * number zero was consumed by a NewSessionTicket record).
	 */
	header[3] = ( uint8_t ) ( sizeof ( server_app_record ) >> 8 );
	header[4] = ( uint8_t ) ( sizeof ( server_app_record ) & 0xff );
	len = tls13_seal ( cipher, server_app_key, sizeof ( server_app_key ),
			   server_app_iv, 1, header, sizeof ( header ),
			   app_payload, sizeof ( app_payload ), TLS_TYPE_DATA,
			   sealed );
	ok ( len == sizeof ( server_app_record ) );
	tls13_okx ( "seal(server)", sealed, server_app_record, len );

	/* Alert records carry an inner content type of alert */
	header[3] = ( uint8_t ) ( sizeof ( alert_record ) >> 8 );
	header[4] = ( uint8_t ) ( sizeof ( alert_record ) & 0xff );
	len = tls13_seal ( cipher, client_app_key, sizeof ( client_app_key ),
			   client_app_iv, 1, header, sizeof ( header ),
			   alert_payload, sizeof ( alert_payload ), TLS_TYPE_ALERT,
			   sealed );
	ok ( len == sizeof ( alert_record ) );
	tls13_okx ( "seal(alert)", sealed, alert_record, len );

	content_type = tls13_open ( cipher, client_app_key,
				    sizeof ( client_app_key ), client_app_iv, 1,
				    header, sizeof ( header ), alert_record,
				    sizeof ( alert_record ), opened, &len );
	ok ( content_type == TLS_TYPE_ALERT );
	ok ( len == sizeof ( alert_payload ) );
	tls13_okx ( "open(alert)", opened, alert_payload, len );

	/* A tampered authentication tag must be rejected */
	header[3] = ( uint8_t ) ( sizeof ( client_app_record ) >> 8 );
	header[4] = ( uint8_t ) ( sizeof ( client_app_record ) & 0xff );
	memcpy ( tampered, client_app_record, sizeof ( tampered ) );
	tampered[ sizeof ( tampered ) - 1 ] ^= 0x01;
	content_type = tls13_open ( cipher, client_app_key,
				    sizeof ( client_app_key ), client_app_iv, 0,
				    header, sizeof ( header ), tampered,
				    sizeof ( tampered ), opened, &len );
	ok ( content_type < 0 );

	/* A tampered ciphertext must be rejected */
	memcpy ( tampered, client_app_record, sizeof ( tampered ) );
	tampered[0] ^= 0x01;
	content_type = tls13_open ( cipher, client_app_key,
				    sizeof ( client_app_key ), client_app_iv, 0,
				    header, sizeof ( header ), tampered,
				    sizeof ( tampered ), opened, &len );
	ok ( content_type < 0 );

	/* A mismatched sequence number must be rejected */
	content_type = tls13_open ( cipher, client_app_key,
				    sizeof ( client_app_key ), client_app_iv, 7,
				    header, sizeof ( header ),
				    client_app_record, sizeof ( client_app_record ),
				    opened, &len );
	ok ( content_type < 0 );
}

/** Test TLS 1.3 ServerHello parsing */
static void tls13_server_hello_test ( void ) {
	struct tls13_server_hello hello;
	uint8_t bad[ sizeof ( server_hello_3 ) ];
	int rc;

	/* RFC 8448 section 3: full handshake, X25519 key share */
	rc = tls13_parse_server_hello ( server_hello_3, sizeof ( server_hello_3 ),
					&hello );
	ok ( rc == 0 );
	ok ( hello.cipher_suite == TLS_AES_128_GCM_SHA256 );
	ok ( hello.version == TLS_VERSION_TLS_1_3 );
	ok ( ! hello.has_psk );
	ok ( hello.has_key_share );
	tls13_okx ( "sh3 key", hello.public_key, server_hello_3_key,
		    sizeof ( hello.public_key ) );

	/* RFC 8448 section 4: pre-shared key accepted as identity 0 */
	rc = tls13_parse_server_hello ( server_hello_4, sizeof ( server_hello_4 ),
					&hello );
	ok ( rc == 0 );
	ok ( hello.cipher_suite == TLS_AES_128_GCM_SHA256 );
	ok ( hello.version == TLS_VERSION_TLS_1_3 );
	ok ( hello.has_psk );
	ok ( hello.selected_identity == 0 );
	ok ( hello.has_key_share );
	tls13_okx ( "sh4 key", hello.public_key, server_hello_4_key,
		    sizeof ( hello.public_key ) );

	/* Truncated messages must be rejected */
	rc = tls13_parse_server_hello ( server_hello_3,
					( sizeof ( server_hello_3 ) - 1 ),
					&hello );
	ok ( rc != 0 );

	/* Non-ServerHello messages must be rejected */
	memcpy ( bad, server_hello_3, sizeof ( bad ) );
	bad[0] = TLS_CLIENT_HELLO;
	rc = tls13_parse_server_hello ( bad, sizeof ( bad ), &hello );
	ok ( rc != 0 );
}

/** Test TLS 1.3 Finished calculation against RFC 8448 section 3 */
static void tls13_finished_test ( void ) {
	uint8_t verify_data[ sizeof ( server_finished ) ];
	uint8_t bad[ sizeof ( finished_transcript ) ];

	/* verify_data = HMAC( ExpandLabel( secret, "finished" ),
	 *                     Transcript-Hash( ClientHello..CertificateVerify ) )
	 */
	tls13_finished ( &sha256_algorithm, server_hs_traffic,
			 finished_transcript, sizeof ( finished_transcript ),
			 verify_data );
	tls13_okx ( "server finished", verify_data, server_finished,
		    sizeof ( verify_data ) );

	/* A single altered transcript byte must change the result */
	memcpy ( bad, finished_transcript, sizeof ( bad ) );
	bad[ sizeof ( bad ) - 1 ] ^= 0x01;
	tls13_finished ( &sha256_algorithm, server_hs_traffic, bad, sizeof ( bad ),
			 verify_data );
	ok ( memcmp ( verify_data, server_finished,
		      sizeof ( verify_data ) ) != 0 );
}

/** Test TLS 1.3 ephemeral key exchange (RFC 8448 section 3) */
static void tls13_key_exchange_test ( void ) {
	struct tls13_key_pair key;
	uint8_t shared[32];

	/* Derive the client public key from its known private key */
	memcpy ( key.private_key, client_private_key_3,
		 sizeof ( key.private_key ) );
	ok ( exchange_share ( &x25519_algorithm, key.private_key,
			      key.public_key ) == 0 );
	tls13_okx ( "X25519 public key", key.public_key, client_public_key_3,
		    sizeof ( key.public_key ) );

	/* Agree the shared secret with the server public key */
	ok ( tls13_shared_secret ( client_private_key_3, server_hello_3_key,
				   shared ) == 0 );
	tls13_okx ( "X25519 shared secret", shared, ecdhe, sizeof ( shared ) );
}

/** Test the TLS 1.3 handshake context (RFC 8448 sections 3 and 4) */
static void tls13_handshake_test ( void ) {
	struct tls13_handshake hs;
	uint8_t c_hs[32];
	uint8_t s_hs[32];
	uint8_t c_ap[32];
	uint8_t s_ap[32];
	uint8_t fin[32];
	size_t ch_sh = ( 196 + 90 );

	/* Section 3: ephemeral handshake with no pre-shared key */
	tls13_handshake_init ( &hs, &sha256_algorithm, NULL, 0, "ext binder" );
	ok ( tls13_handshake_update ( &hs, finished_transcript,
				      ch_sh ) == 0 );

	/* Reproduce the (EC)DHE using the RFC's client private key */
	memcpy ( hs.key.private_key, client_private_key_3,
		 sizeof ( hs.key.private_key ) );
	ok ( tls13_handshake_exchange ( &hs, server_hello_3_key ) == 0 );
	tls13_okx ( "hs secret", hs.handshake, handshake_secret,
		    sizeof ( hs.handshake ) );

	tls13_handshake_derive ( &hs, hs.handshake, "c hs traffic", c_hs );
	tls13_handshake_derive ( &hs, hs.handshake, "s hs traffic", s_hs );
	tls13_okx ( "c hs traffic", c_hs, client_hs_traffic_3, sizeof ( c_hs ) );
	tls13_okx ( "s hs traffic", s_hs, server_hs_traffic, sizeof ( s_hs ) );

	/* Server Finished: transcript extends to CertificateVerify */
	ok ( tls13_handshake_update ( &hs, &finished_transcript[ch_sh],
				      ( sizeof ( finished_transcript ) -
					ch_sh ) ) == 0 );
	tls13_handshake_finished ( &hs, s_hs, fin );
	tls13_okx ( "server finished", fin, server_finished, sizeof ( fin ) );

	/* Client Finished: transcript extends by the server Finished */
	ok ( tls13_handshake_update ( &hs, server_finished_msg_3,
				      sizeof ( server_finished_msg_3 ) ) == 0 );
	tls13_handshake_finished ( &hs, c_hs, fin );
	tls13_okx ( "client finished", fin, &client_finished_msg_3[4],
		    sizeof ( fin ) );

	/* Application traffic secrets: transcript to the server Finished */
	tls13_handshake_master ( &hs );
	tls13_okx ( "master secret", hs.master, master_secret,
		    sizeof ( hs.master ) );
	tls13_handshake_derive ( &hs, hs.master, "c ap traffic", c_ap );
	tls13_handshake_derive ( &hs, hs.master, "s ap traffic", s_ap );
	tls13_okx ( "c ap traffic", c_ap, client_ap_traffic_3,
		    sizeof ( c_ap ) );
	tls13_okx ( "s ap traffic", s_ap, server_ap_traffic_3,
		    sizeof ( s_ap ) );

	/* Section 4: pre-shared key handshake */
	tls13_handshake_init ( &hs, &sha256_algorithm, resumption_psk,
			       sizeof ( resumption_psk ), "res binder" );
	tls13_okx ( "psk early secret", hs.early, resumption_early,
		    sizeof ( hs.early ) );

	/* Shake hands as the client: ClientHello then ServerHello */
	ok ( tls13_handshake_update ( &hs, client_hello_4,
				      sizeof ( client_hello_4 ) ) == 0 );
	ok ( tls13_handshake_update ( &hs, server_hello_4,
				      sizeof ( server_hello_4 ) ) == 0 );
	memcpy ( hs.key.private_key, client_private_key_4,
		 sizeof ( hs.key.private_key ) );
	ok ( tls13_handshake_exchange ( &hs, server_hello_4_key ) == 0 );

	tls13_handshake_derive ( &hs, hs.handshake, "c hs traffic", c_hs );
	tls13_handshake_derive ( &hs, hs.handshake, "s hs traffic", s_hs );
	tls13_okx ( "psk c hs traffic", c_hs, client_hs_traffic_4,
		    sizeof ( c_hs ) );
	tls13_okx ( "psk s hs traffic", s_hs, server_hs_traffic_4,
		    sizeof ( s_hs ) );

	/* Server Finished: transcript extends to EncryptedExtensions */
	ok ( tls13_handshake_update ( &hs, encrypted_extensions_4,
				      sizeof ( encrypted_extensions_4 ) ) == 0 );
	tls13_handshake_finished ( &hs, s_hs, fin );
	tls13_okx ( "psk server finished", fin, &server_finished_msg_4[4],
		    sizeof ( fin ) );

	/* Application traffic secrets: transcript to the server Finished */
	ok ( tls13_handshake_update ( &hs, server_finished_msg_4,
				      sizeof ( server_finished_msg_4 ) ) == 0 );
	tls13_handshake_master ( &hs );
	tls13_handshake_derive ( &hs, hs.master, "c ap traffic", c_ap );
	tls13_handshake_derive ( &hs, hs.master, "s ap traffic", s_ap );
	tls13_okx ( "psk c ap traffic", c_ap, client_ap_traffic_4,
		    sizeof ( c_ap ) );
	tls13_okx ( "psk s ap traffic", s_ap, server_ap_traffic_4,
		    sizeof ( s_ap ) );

	/* Client Finished: the trace uses 0-RTT, so the transcript also
	 * includes the EndOfEarlyData message. */
	ok ( tls13_handshake_update ( &hs, end_of_early_data_4,
				      sizeof ( end_of_early_data_4 ) ) == 0 );
	tls13_handshake_finished ( &hs, c_hs, fin );
	tls13_okx ( "psk client finished", fin, &client_finished_msg_4[4],
		    sizeof ( fin ) );

	/* A transcript overflow must be detected */
	tls13_handshake_init ( &hs, &sha256_algorithm, NULL, 0, "ext binder" );
	ok ( tls13_handshake_update ( &hs, finished_transcript,
				      sizeof ( finished_transcript ) ) == 0 );
	ok ( tls13_handshake_update ( &hs, finished_transcript,
				      200 ) != 0 );
}

/** Test TLS 1.3 key schedule against RFC 8448 section 3 */
static void tls13_test_exec ( void ) {
	struct digest_algorithm *digest = &sha256_algorithm;
	uint8_t secret[ digest->digestsize ];
	uint8_t key[ sizeof ( server_write_key ) ];
	uint8_t iv[ sizeof ( server_write_iv ) ];
	uint8_t binder[ digest->digestsize ];

	/* Early Secret = HKDF-Extract( 0, 0 ) */
	tls13_early_secret ( digest, NULL, 0, secret );
	tls13_okx ( "early", secret, early_secret, sizeof ( secret ) );

	/* derived = Derive-Secret( Early, "derived", "" ) */
	tls13_derive_secret ( digest, secret, "derived", NULL, 0, secret );
	tls13_okx ( "derived(early)", secret, derived_early, sizeof ( secret ) );

	/* Handshake Secret = HKDF-Extract( derived, (EC)DHE ) */
	tls13_early_secret ( digest, NULL, 0, secret );
	tls13_handshake_secret ( digest, secret, ecdhe, sizeof ( ecdhe ),
				 secret );
	tls13_okx ( "handshake", secret, handshake_secret, sizeof ( secret ) );

	/* derived = Derive-Secret( Handshake, "derived", "" ) */
	tls13_derive_secret ( digest, secret, "derived", NULL, 0, secret );
	tls13_okx ( "derived(handshake)", secret, derived_handshake,
		    sizeof ( secret ) );

	/* Master Secret = HKDF-Extract( derived, 0 ) */
	tls13_handshake_secret ( digest, early_secret, ecdhe, sizeof ( ecdhe ),
				 secret );
	tls13_master_secret ( digest, secret, secret );
	tls13_okx ( "master", secret, master_secret, sizeof ( secret ) );

	/* Traffic key / IV from the server handshake traffic secret */
	tls13_traffic_key ( digest, server_hs_traffic, key, sizeof ( key ),
			    iv, sizeof ( iv ) );
	tls13_okx ( "write key", key, server_write_key, sizeof ( key ) );
	tls13_okx ( "write iv", iv, server_write_iv, sizeof ( iv ) );

	/* Early Secret and PSK binder (RFC 8448 section 4) */
	tls13_early_secret ( digest, resumption_psk, sizeof ( resumption_psk ),
			     secret );
	tls13_okx ( "psk early", secret, resumption_early, sizeof ( secret ) );
	tls13_binder ( digest, secret, "res binder", ch_prefix,
		       sizeof ( ch_prefix ), binder );
	tls13_okx ( "psk binder", binder, resumption_binder, sizeof ( binder ) );

	/* ClientHello construction */
	tls13_client_hello_test();

	/* Record protection */
	tls13_nonce_test();
	tls13_record_test();

	/* ServerHello parsing and Finished calculation */
	tls13_server_hello_test();
	tls13_finished_test();

	/* Key exchange and handshake context */
	tls13_key_exchange_test();
	tls13_handshake_test();
}

